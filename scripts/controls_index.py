#!/usr/bin/env python3
"""Build controls/controls.json from the control files, so the Markdown and the machine-readable index never drift.

  python3 scripts/controls_index.py           # write controls/controls.json
  python3 scripts/controls_index.py --check   # exit 1 if the file is out of date (CI uses this)

Each control file starts with a table (Control ID, Evidence number, Applies to, Owner, Review frequency,
Limitations) followed by an Objective line. The index also records the evidence kinds, the indicative framework
references, and the verify sections. Python 3 standard library only.
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FIELDS = {"Control ID": "id", "Evidence number": "evidence_number", "Applies to": "applies_to", "Owner (role)": "owner",
          "Review frequency": "review_frequency", "Limitations": "limitations"}


def read(p):
    with open(p, encoding="utf-8") as fh:
        return fh.read()


def parse(path):
    t = read(path)
    title = t.split("\n", 1)[0].lstrip("# ").strip()
    out = {"file": os.path.basename(path), "title": title.split(". ", 1)[1] if ". " in title else title}
    for label, key in FIELDS.items():
        m = re.search(rf"^\| \*\*{re.escape(label)}\*\* \| (.*) \|$", t, re.M)
        out[key] = m.group(1).strip() if m else None
    num = re.match(r"(\d+)", out["evidence_number"] or "")
    out["evidence_number"] = num.group(1) if num else None
    days = re.search(r"older than (\d+) days", out["review_frequency"] or "")
    out["freshness_days"] = int(days.group(1)) if days else None
    m = re.search(r"^\*\*Objective:\*\* (.*)$", t, re.M)
    out["objective"] = m.group(1).strip() if m else None
    done = re.search(r"## Done when\n\n(.*?)\n\n## ", t, re.S)
    out["done_when"] = [re.sub(r"^- \[ \] ", "", l) for l in (done.group(1).splitlines() if done else []) if l.startswith("- [ ]")]
    kinds = {}
    for label, key in (("Configuration", "config"), ("Operational", "operational"), ("Effectiveness", "effectiveness"), ("Independent assurance", "assurance")):
        m = re.search(rf"^- \*\*{label}:\*\* (.*)$", t, re.M)
        kinds[key] = m.group(1).strip() if m else None
    out["evidence_kinds"] = kinds
    refs = re.search(r"## Indicative framework references\n\n(.*?)\n\n", t, re.S)
    out["indicative_references"] = refs.group(1).strip() if refs else None
    out["verify_section"] = f"verify/*.md#{out['evidence_number']}" if out["evidence_number"] else None
    return out


def build():
    controls = [parse(p) for p in sorted(glob.glob(os.path.join(ROOT, "controls", "[0-9][0-9]-*.md")))]
    return {"note": "Generated by scripts/controls_index.py from controls/*.md. Do not edit by hand.", "controls": controls}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    path = os.path.join(ROOT, "controls", "controls.json")
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in argv:
        current = read(path) if os.path.exists(path) else ""
        if current != text:
            print("controls/controls.json is out of date: run python3 scripts/controls_index.py", file=sys.stderr)
            return 1
        print("controls.json is up to date")
        return 0
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
