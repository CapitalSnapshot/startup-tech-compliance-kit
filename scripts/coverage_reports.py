#!/usr/bin/env python3
"""Generate the coverage reports in docs/coverage/ from controls/mappings.json.

  python3 scripts/coverage_reports.py --build    # write docs/coverage/*.md
  python3 scripts/coverage_reports.py --check    # exit 1 if the committed reports differ from a fresh build, or the mappings are invalid

The reports describe the state of the kit's mappings: counts by coverage status and review label, the records that still need
work, and the editions mapped. They contain counts and lists only. There are no percentages, scores or readiness wording, because
they are not a measure of anyone's compliance. The date shown is the data_date recorded in mappings.json, not the day the file was
built, so a fresh build is reproducible. Python 3 standard library only.
"""
import importlib.util
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT_DIR = os.path.join(ROOT, "docs", "coverage")
FRAMEWORKS = [("SOC 2", "soc2"), ("ISO/IEC 27001", "iso27001"), ("GDPR", "gdpr"), ("DORA", "dora")]
STATUSES = ["covered", "covered in part", "not covered", "not applicable", "not assessed", "needs expert review"]
LABELS = ["community draft", "maintainer reviewed", "specialist reviewed"]
NOTICE = ("These reports describe the state of the kit's mappings. They are not a measure of anyone's compliance and the mappings have "
          "not been verified by a specialist unless the review label says so.")


def _vm():
    spec = importlib.util.spec_from_file_location("validate_mappings", os.path.join(ROOT, "scripts", "validate_mappings.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _load(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def _clean(text):
    """Remove the pending marker syntax so a sentence reads normally."""
    t = text.strip()
    if t.startswith("<pending"):
        t = t[len("<pending"):].lstrip(":").strip()
        if t.endswith(">"):
            t = t[:-1].strip()
    return t


_SENTENCE_END = re.compile(r"(?<!Art)(?<!Arts)(?<!Ch)\.\s+(?=[A-Z])")


def _first_sentence(text):
    t = _clean(text)
    m = _SENTENCE_END.search(t)
    t = (t[: m.start() + 1] if m else t).rstrip()
    return (t[:1].upper() + t[1:]) if t else t


def _counts(recs, key, order):
    c = {k: 0 for k in order}
    for r in recs:
        c[key(r)] = c.get(key(r), 0) + 1
    return c


def _record_line(r, titles, with_reason=None):
    refs = ", ".join(r["source_reference"])
    line = f"- `{r['id']}` ({titles.get(r['control_id'], r['control_id'])}): {refs}"
    if with_reason:
        line += f": {with_reason}"
    return line


def framework_report(fw, slug, recs, incomplete, titles, data_date):
    mine = [r for r in recs if r["framework"] == fw]
    inc = {rid: fields for rid, fields in incomplete}
    editions = sorted({r["edition"] for r in mine})
    labels = _counts(mine, lambda r: r["review"]["label"], LABELS)
    status = _counts(mine, lambda r: r["coverage_status"], STATUSES)
    out = [f"# Coverage report: {fw}", "",
           "**Review labels: " + ", ".join(f"{k} {v}" for k, v in labels.items()) + ".**", "",
           f"> {NOTICE}", "",
           f"Data as of {data_date} (the date recorded in [`mappings.json`](../../controls/mappings.json), so this page can be rebuilt exactly). "
           f"Edition mapped: {'; '.join(editions)}. Records: {len(mine)}. Generated by `scripts/coverage_reports.py`; do not edit by hand.", "",
           "## Counts by coverage status", "", "| Coverage status | Records |", "|---|---|"]
    out += [f"| {s} | {status[s]} |" for s in STATUSES] + [f"| **Total** | {len(mine)} |", "",
            "## Counts by review label", "", "| Review label | Records |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in labels.items()] + [""]

    def section(title, intro, status_name, reason=lambda r: None):
        rs = [r for r in mine if r["coverage_status"] == status_name]
        out.extend([f"## {title}", "", intro, ""])
        out.extend([_record_line(r, titles, reason(r)) for r in rs] if rs else ["None."])
        out.append("")

    section("Not assessed", "Nothing has been judged for these records yet. **Not assessed is neither a gap nor a pass.**", "not assessed")
    section("Needs expert review", "An assessment was attempted but needs a qualified reviewer, or the source text could not be read for the mapping.",
            "needs expert review", lambda r: _first_sentence(r["limitations"]))
    section("Not covered", "The requirement is relevant to the reader and the kit does not address it. These are actual gaps.", "not covered",
            lambda r: _first_sentence(r["mapping_rationale"]))
    section("Not applicable", "A deliberate, documented exclusion, with a reason.", "not applicable", lambda r: _first_sentence(r["mapping_rationale"]))
    section("Covered", "A maintainer or specialist reviewed the record and recorded that the kit addresses what the requirement asks of the kit's scope. **It is not a statement that anyone meets the requirement.** The review label says who reviewed it.", "covered")
    section("Covered in part", "The kit addresses some of what the requirement asks. Each record lists what is not covered. This is the authors' draft judgement and has not been reviewed unless the review label says so.", "covered in part")
    out.extend(["## Incomplete records", "",
                "A record is incomplete while a field still holds an explicit pending placeholder that must be filled from the source.", ""])
    ir = [r for r in mine if r["id"] in inc]
    out.extend([f"- `{r['id']}`: pending {', '.join(inc[r['id']])}" for r in ir] if ir else ["None."])
    out.extend(["", "## How to read this report", "",
                "- A count describes the mappings, not your organisation.",
                "- The six coverage statuses and three review labels are defined in [`docs/review-labels.md`](../review-labels.md).",
                "- A requirement that is not listed in the mappings has not been assessed.", ""])
    return "\n".join(out)


def index_report(recs, incomplete, data_date):
    inc = {rid for rid, _ in incomplete}
    labels = _counts(recs, lambda r: r["review"]["label"], LABELS)
    out = ["# Coverage reports", "",
           "**Review labels: " + ", ".join(f"{k} {v}" for k, v in labels.items()) + ".**", "",
           f"> {NOTICE}", "",
           f"Data as of {data_date} (the date recorded in [`mappings.json`](../../controls/mappings.json)). Counts and lists only. "
           "Generated by `scripts/coverage_reports.py`; do not edit by hand.", "",
           "| Framework | " + " | ".join(STATUSES) + " | Records | Incomplete |", "|---|" + "---|" * (len(STATUSES) + 2)]
    tot = {s: 0 for s in STATUSES}
    for fw, slug in FRAMEWORKS:
        rs = [r for r in recs if r["framework"] == fw]
        c = _counts(rs, lambda r: r["coverage_status"], STATUSES)
        for s in STATUSES:
            tot[s] += c[s]
        out.append(f"| [{fw}]({slug}.md) | " + " | ".join(str(c[s]) for s in STATUSES) + f" | {len(rs)} | {sum(1 for r in rs if r['id'] in inc)} |")
    out.append("| **Total** | " + " | ".join(f"**{tot[s]}**" for s in STATUSES) + f" | **{len(recs)}** | **{len(inc)}** |")
    out.extend(["", "Definitions: [`docs/review-labels.md`](../review-labels.md). The mappings themselves: [`controls/framework-mappings.md`](../../controls/framework-mappings.md).", ""])
    return "\n".join(out)


def build_reports(data, controls, incomplete):
    titles = {c["id"]: c["title"] for c in controls}
    recs = data["records"]
    files = {"README.md": index_report(recs, incomplete, data["data_date"])}
    for fw, slug in FRAMEWORKS:
        files[f"{slug}.md"] = framework_report(fw, slug, recs, incomplete, titles, data["data_date"])
    return files


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    vm = _vm()
    try:
        data, schema, controls = _load(vm.MAPPINGS), _load(vm.SCHEMA), _load(vm.CONTROLS)["controls"]
    except (OSError, ValueError) as e:
        print(f"error: could not read an input file: {e}", file=sys.stderr)
        return 2
    errors, incomplete = vm.validate(data, schema, {c["id"] for c in controls})
    if errors:
        print("not generating: the mappings are invalid\n" + "\n".join(f"  {e}" for e in errors), file=sys.stderr)
        return 1
    files = build_reports(data, controls, incomplete)
    if "--check" in argv:
        stale = []
        for name, text in files.items():
            path = os.path.join(OUT_DIR, name)
            try:
                with open(path, encoding="utf-8") as fh:
                    cur = fh.read()
            except OSError:
                cur = None
            if cur != text:
                stale.append(name)
        extra = sorted(set(os.listdir(OUT_DIR)) - set(files)) if os.path.isdir(OUT_DIR) else []
        if stale or extra:
            print("docs/coverage is out of date: run python3 scripts/coverage_reports.py --build "
                  f"(stale: {', '.join(stale) or 'none'}; unexpected files: {', '.join(extra) or 'none'})", file=sys.stderr)
            return 1
        print("coverage reports are up to date")
        return 0
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8") as fh:
            fh.write(text)
    print(f"wrote {len(files)} files to {os.path.relpath(OUT_DIR, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
